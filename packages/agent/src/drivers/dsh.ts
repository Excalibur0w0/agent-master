import { execFile } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { homedir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { AmError, poll, sleep, type Driver } from "./types.ts";

const REPORTER = fileURLToPath(new URL("../../dsh/reporter.js", import.meta.url));

/** The TUI launcher from deepseek-harness-tui; plain `dsh` ships no terminal profile. */
const BIN = "dshcli";

const cacheDir = () => join(process.env.XDG_CACHE_HOME ?? join(homedir(), ".cache"), "agent-master");

/** A --patch overlay that mounts am's reporter next to the TUI's own plugins. */
export function dshReporterPatch(reporter = REPORTER, replyDir = join(cacheDir(), "dsh-replies")): string {
  return [
    "# Generated by `am start --kind dsh`: reports the TUI's state to am.",
    "- insert:",
    "    - id: am-reporter",
    `      name: ${JSON.stringify(reporter)}`,
    "      config:",
    `        replyDir: ${JSON.stringify(replyDir)}`,
    "",
  ].join("\n");
}

/** A --patch overlay that picks the model, as `--model <provider>/<model>`. */
export function dshModelPatch(model: string): string {
  const slash = model.indexOf("/");
  if (slash <= 0 || slash === model.length - 1) throw new AmError("usage", `dsh expects --model <provider>/<model>, got: ${model}`);
  return [
    "- id: agent-default-model",
    "  config:",
    `    provider: ${JSON.stringify(model.slice(0, slash))}`,
    `    model: ${JSON.stringify(model.slice(slash + 1))}`,
    "",
  ].join("\n");
}

/** Overlays go to the cache, named by content, so the user's dsh profile stays untouched. */
async function patchFile(name: string, content: string): Promise<string> {
  const path = join(cacheDir(), `dsh-${name}-${createHash("sha256").update(content).digest("hex").slice(0, 12)}.yml`);
  if ((await readFile(path, "utf8").catch(() => "")) !== content) {
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, content);
  }
  return path;
}

function onPath(command: string): Promise<boolean> {
  return new Promise((resolve) => execFile("/bin/sh", ["-c", 'command -v "$1"', "sh", command], (error) => resolve(!error)));
}

/** Questions have no keys am can answer for the user. */
function assertApproval(record: { name: string; pending: string }): void {
  if (record.pending.startsWith("question-")) {
    throw new AmError("unsupported", `${record.name} is asking a question; answer it in its session (am open ${record.name})`);
  }
}

export const dsh: Driver = {
  kind: "dsh",
  // The reporter counts the line as soon as the TUI submits it.
  acceptTimeoutMs: 5000,

  async preflight() {
    return (await onPath(BIN)) ? [] : [`${BIN} is not on PATH: install deepseek-harness-tui and link bin/dshcli into a PATH directory`];
  },

  async launch({ model, args }) {
    const patches = [await patchFile("reporter", dshReporterPatch())];
    if (model) patches.push(await patchFile("model", dshModelPatch(model)));
    return { command: [BIN, ...patches.flatMap((path) => ["--patch", path]), ...args] };
  },

  async waitReady(_tmux, reload, deadline) {
    const ready = await poll(async () => {
      const record = await reload();
      if (record.paneDead) throw new AmError("exited", "dsh exited right after starting");
      return record.event === "SessionStart" ? true : undefined;
    }, deadline);
    if (!ready) throw new AmError("start_timeout", "dsh did not finish starting in time (check its session with am open)");
    // The reporter fires as the TUI opens; give its input box a moment to take keys.
    await sleep(300);
  },

  async status(record) {
    if (record.paneDead) return { state: "exited", detail: "" };
    return { state: record.state, detail: record.detail };
  },

  async promptMarker(record) {
    return String(record.seq);
  },

  async readReply(record) {
    if (!record.transcript) throw new AmError("no_session", `not sure yet where ${record.name} keeps its replies (it has not reported a session)`);
    return readFile(record.transcript, "utf8").catch(() => "");
  },

  async approve(tmux, record, scope) {
    if (scope === "always") throw new AmError("unsupported", "dsh only supports one-time approval (am approve without --always)");
    assertApproval(record);
    await tmux.sendKeys(record.paneId, "y");
  },

  async deny(tmux, record) {
    assertApproval(record);
    await tmux.sendKeys(record.paneId, "n");
  },

  async interrupt(tmux, record) {
    await tmux.sendKeys(record.paneId, "Escape");
  },
};
